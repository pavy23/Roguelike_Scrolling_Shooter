def main() -> None:
    data = json.loads(WAVES.read_text(encoding="utf-8"))
    by_id = {b["id"]: b for b in data["bosses"]}
    fortress = by_id["boss_fortress"]

    rebuilt = []
    for template in BOSSES:
        if template.get("_keep"):
            rebuilt.append(fortress)
            continue
        rebuilt.append(template)

    # Verify fortress untouched identity
    assert rebuilt[2]["id"] == "boss_fortress"
    assert rebuilt[2]["hp"] == 19600
    assert rebuilt[2]["warship"]["id"] == "fortress_warship"

    # HP sum checks
    for b in rebuilt:
        if "parts" in b and b["parts"]:
            s = sum(p["hp"] for p in b["parts"])
            assert s == b["hp"], f"{b['id']} parts sum {s} != hp {b['hp']}"

    data["bosses"] = rebuilt
    WAVES.write_text(
        json.dumps(data, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(rebuilt)} bosses to {WAVES}")
    for b in rebuilt:
        parts = len(b.get("parts") or [])
        phases = len(b.get("phases") or [])
        form2 = "form2" if b.get("form2") else "-"
        print(f"  {b['id']:22} hp={b['hp']:6} parts={parts} phases={phases} {form2}")


if __name__ == "__main__":
    main()
